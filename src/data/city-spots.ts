export function getCitySpots(address: Address | null): CitySpot[] | null {
  const city = normalizeCityName(address?.city ?? address?.region ?? null);
  if (!city) return null;
  const seeds = CITY_SPOTS[city];
  if (!seeds) return null;
  return seeds.map((seed) => spot(city, seed));
}