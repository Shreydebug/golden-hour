import type { Address, PhotographySpot, SpotCategory } from '@/types';

export interface CitySpot extends PhotographySpot {
  review: string;
  reviewSource: string;
  reviewCount?: number;
}

interface CitySpotSeed {
  name: string;
  description: string;
  category: SpotCategory;
  latitude: number;
  longitude: number;
  rating: number;
  distance: number;
  goldenHourQuality: number;
  crowdLevel: 'low' | 'medium' | 'high';
  parking: boolean;
  walkingDistance: number;
  bestTime: string;
  tags: string[];
  review: string;
  reviewSource: string;
  reviewCount?: number;
}

const CITY_ALIASES: Record<string, string> = {
  'new delhi': 'delhi',
  bombay: 'mumbai',
  bengaluru: 'bangalore',
  'bangaluru': 'bangalore',
  madras: 'chennai',
  calcutta: 'kolkata',
  'hong kong': 'hong kong',
  'los angeles': 'los angeles',
};

export function normalizeCityName(city: string | null | undefined): string | null {
  if (!city) return null;
  const cleaned = city
    .toLowerCase()
    .trim()
    .replace(/\s+city$/, '')
    .replace(/[^a-z\s]/g, '')
    .trim();
  if (!cleaned) return null;
  return CITY_ALIASES[cleaned] ?? cleaned;
}

function spot(cityKey: string, seed: CitySpotSeed): CitySpot {
  const bestViewingDirection = /sunrise|morning/i.test(seed.bestTime)
    ? 'East'
    : /blue/i.test(seed.bestTime)
      ? 'Southwest'
      : 'West';

  return {
    id: `${cityKey}-${seed.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')}`,
    name: seed.name,
    description: seed.description,
    category: seed.category,
    latitude: seed.latitude,
    longitude: seed.longitude,
    imageUrl: '',
    rating: seed.rating,
    distance: seed.distance,
    goldenHourQuality: seed.goldenHourQuality,
    crowdLevel: seed.crowdLevel,
    parking: seed.parking,
    walkingDistance: seed.walkingDistance,
    bestTime: seed.bestTime,
    bestViewingDirection,
    tags: [...seed.tags, seed.bestTime.toLowerCase().replace(/\s+/g, ' ')],
    review: seed.review,
    reviewSource: seed.reviewSource,
    reviewCount: seed.reviewCount,
  };
}

