function resolveKey(...parts: Array<string | null | undefined>): string | null {
  for (const part of parts) {
    if (!part) continue;
    const key = normalizeKey(part);
    if (STATE_PLACES[key]) return key;
    const alias = REGION_ALIASES[key];
    if (alias && STATE_PLACES[alias]) return alias;
  }
  return null;
}

export function getStatePlaces(address: Address | null | undefined): StatePlacesResult | null {
  if (!address) return null;
  const key = resolveKey(address.region, address.city, address.country);
  if (!key) return null;
  const items = STATE_PLACES[key];
  const label = REGION_TITLES[key];
  return {
    key,
    title: label?.title ?? 'Places worth the drive',
    sub: label?.sub ?? 'Featured locations, curated light and the spots everyone is talking about.',
    items,
  };
}